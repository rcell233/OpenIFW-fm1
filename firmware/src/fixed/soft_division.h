static inline uint32_t ifw_recip16_exact(uint32_t d) {
    uint32_t r=ifw_recip16_seed[(d>>6)-512u];
    uint32_t error=UINT32_MAX-d*r;
    r+=(uint32_t)(((uint64_t)r*error)>>32);
    /* After refinement d*r < 2^32, so unsigned negation is its remainder. */
    if(0u-d*r>=d)r++;
    return r;
}
static inline uint32_t ifw_div_recip16(uint32_t n,uint32_t d,uint32_t reciprocal) {
    uint32_t q=(uint32_t)(((uint64_t)n*reciprocal)>>32);
    if(n-q*d>=d)q++;
    return q;
}
