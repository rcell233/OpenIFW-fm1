#!/usr/bin/env python3
"""Deterministic Q14 reciprocal gain, no floating-point or target division."""
from pathlib import Path
import sys
root=Path(__file__).resolve().parents[1]
values=[min(16384,24576*16384//(i*256)) if i else 16384 for i in range(513)]
text='/* SPDX-License-Identifier: GPL-3.0-only\n * Generated by tools/generate_output_bus.py; do not edit. */\n'
text+='static const uint16_t ifw_bus_gain_q14[513] = {\n'
text+='\n'.join('    '+','.join(str(v) for v in values[i:i+16])+',' for i in range(0,len(values),16))
text+='\n};\n'
path=root/'firmware/src/output_bus_table.h'
if '--check' in sys.argv:
    assert path.read_text()==text,'Output gain table is stale'
else:path.write_text(text)
