#!/usr/bin/env python3
"""Generate stable parameter IDs and the unmodified upstream envelope curve.

The schema describes OpenIFW's DSP defaults, not a factory preset.
"""
from pathlib import Path
import json
import re
import math

ROOT = Path(__file__).resolve().parents[1]
rows = []

def add(name, default=0, bounds=None, kind="number", status="active"):
    rows.append(dict(id=len(rows), name=name, default=default, bounds=bounds,
                     kind=kind, status=status))

osc = [("Sync", "Off", None), ("Semi", 0, [-36,36]), ("Tune", 0, [-50,50]),
       ("SawLevel",0,[0,10]), ("TriLevel",0,[0,10]), ("PwmLevel",0,[0,10]),
       ("PwmWidth",5,[0,10]), ("NoiseLevel",0,[0,10]), ("NoiseLoFi",0,[0,10]),
       ("Waveform2","TRI",None), ("Output1","Off",None), ("Output2","Off",None)]
flt = [("Type","LPF24",None), ("Frequency",0,[0,10]), ("Resonance",0,[0,10]),
       ("Breath",0,[-10,10]), ("KeyTrack",0,[-10,10]), ("BreathSubMod","BREATH",None)]
eg = [("Attack",0,[0,10]), ("Decay",5,[0,10]), ("Sustain",10,[0,10]),
      ("Release",0,[0,10]), ("Retrigger","Off",None)]
lfo = [("Waveform","TRI",None), ("Speed",2,[0,10]), ("KeySync","Off",None),
       ("BPMSync","Off",None), ("BpmSync","Off",None), ("Beat","1/4",None)]
mod = [("Source1","None",None), ("Source2","None",None),
       ("Destination","None",None), ("Depth",0,[-10,10])]
for prefix, count, fields in [("Osc",4,osc),("Filter",2,flt),("Eg",4,eg),("Lfo",2,lfo),("Mod",8,mod)]:
    for i in range(1,count+1):
        for suffix, default, bounds in fields:
            add(f"{prefix}{i}{suffix}",default,bounds,"text" if isinstance(default,str) else "number")
for n,d,b in [("Filter3Enabled","Off",None),("Filter3Stage",2,[2,24]),
              ("Filter3Frequency",0,[0,10]),("Filter3Resonance",0,[-10,10]),("Filter3Mix",0,[-10,10])]:
    add(n,d,b,"text" if isinstance(d,str) else "number")
for i in (1,2):
    add(f"Amp{i}Level",10,[0,10]); add(f"Amp{i}Breath",10,[0,10])
    add(f"Amp{i}BreathSubMod","BREATH",kind="text")
for n,d,b in [("FilterConnection","Parallel 2",None),("Transpose",0,[-24,24]),
              ("PitchBendRange",2,[0,24]),("MasterTune",0,[-50,50]),("MasterLevel",10,[0,10]),
              ("GateOpenSmoothTime",2,None),("GateCloseSmoothTime",15,None),
              ("BreathSmoothTime",12,None),("PitchBendSmoothTime",5,None),("GlideSmoothTime",5,None),
              ("GlideMinimumSpeed",0,[0,1]),("GlideSpeed",0,[0,10]),
              ("GlideMidiEnabled","Off",None),("GlideMode","Time",None),
              ("ExciterFrequency",0,[0,10]),("ExciterMix",0,[0,10]),
              ("EnhancerMix",0,[0,10]),("EnhancerDelayL",0,[0,100]),("EnhancerDelayR",0,[0,100]),
              ("EqLowGain",0,[-12,12]),("EqHighGain",0,[-12,12])]:
    add(n,d,b,"text" if isinstance(d,str) else "number")
out = ROOT/"src/reference"
header = "/* Generated by tools/generate_tables.py; do not edit. */\n#ifndef IFW_PARAMS_H\n#define IFW_PARAMS_H\n"
header += "enum {\n" + "".join(f"    P_{r['name']} = {r['id']},\n" for r in rows)
header += f"    IFW_PARAM_COUNT = {len(rows)}\n}};\n"
for name,fields in [("OSC",osc),("FILTER",flt),("EG",eg),("LFO",lfo),("MOD",mod)]:
    header += f"#define IFW_{name}_STRIDE {len(fields)}\n"
header += "typedef struct { const char *name; double number; const char *text; } IFWParamDef;\n"
header += "extern const IFWParamDef ifw_param_defs[IFW_PARAM_COUNT];\n#endif\n"
(out/"params.h").write_text(header)
source = '#include "params.h"\nconst IFWParamDef ifw_param_defs[IFW_PARAM_COUNT] = {\n'
for r in rows:
    d=r['default']; source += f'    {{"{r["name"]}", {d if isinstance(d,(int,float)) else 0}, {json.dumps(d) if isinstance(d,str) else "0"}}},\n'
(out/"params.c").write_text(source+"};\n")
(ROOT/"docs/parameters.json").write_text(json.dumps(rows,indent=2)+"\n")
env = (ROOT/"vendor/openifw/dsp/envelope.js").read_text()
curve = re.search(r"const CURVE = new Float64Array\(\[([\s\S]*?)\]\);",env).group(1)
(out/"envelope_curve.h").write_text("/* OpenIFW envelope.js, MIT, exact decimal constants. */\nstatic const double decay_curve[] = {"+curve+"};\n")
(ROOT/"firmware/src/fixed/decay_curve_q31.h").write_text(
    "/* Generated from OpenIFW's curve; Q31, 1.0 = INT32_MAX. */\nstatic const int32_t decay_curve_q31[] = {\n" +
    ",\n".join("    "+", ".join(str(round(float(x)*2147483647)) for x in re.findall(r"[\d.]+",curve)[i:i+8])
                for i in range(0,len(re.findall(r"[\d.]+",curve)),8))+"\n};\n")
print(f"generated {len(rows)} parameter IDs and {len(re.findall(r'[0-9.]+',curve))} curve points")

def clock(knots,v):
    i=1
    while i<len(knots)-1 and v>knots[i][0]: i+=1
    x0,y0=knots[i-1]; x1,y1=knots[i]
    return y0*math.exp(math.log(y1/y0)*(v-x0)/(x1-x0))
attack=[(0,.0028046),(2,.0142461),(3,.0320786),(5,.1625949),(8,1.8569279)]
half=[(0,.001794804017599996),(4.6,.03928657751073832),(5.6,.0766502365383003),(7,.19640721210337342),(8,.3823215381376901)]
tables = {
    'attack_step_q31':[round(2147483647/(44100*clock(attack,i/100))) for i in range(1001)],
    'decay_step_q22':[round(100*(1<<22)/(44100*clock(half,i/100))) for i in range(1001)],
    'rate_q18':[round(math.exp(.8742323893*(i-1000)/100)*(1<<18)) for i in range(2001)],
}
data='/* Generated for 44100 Hz. Integer-only FM-1 envelope coefficients. */\n'
for name,values in tables.items():
    data+=f'static const uint32_t {name}[] = {{\n'
    data+=',\n'.join('    '+', '.join(f'{n}u' for n in values[i:i+8]) for i in range(0,len(values),8))+'\n};\n'
(ROOT/'firmware/src/fixed/envelope_tables.h').write_text(data)
