#!/usr/bin/env python3
"""Build-time floating point only. All emitted DSP tables are integers."""
import math,json
from pathlib import Path
R=Path(__file__).resolve().parents[1]
F=R/'firmware/src/fixed'
q=lambda x,b:round(x*(1<<b))
tables={}
tables['ifw_sine_table']=[q(math.sin(2*math.pi*i/1024),20) for i in range(1025)]
tables['ifw_semitone_fraction']=[q(2**(i/(1024*12)),30) for i in range(1025)]
tables['ifw_octave_fraction']=[q(2**(i/1024),30) for i in range(1025)]
tables['ifw_note_base']=[q(440*2**((120+i-69)/12)/88200,32) for i in range(12)]
tables['ifw_glide_recip']=[q(1/(88.2*2**((i/256)*1.2)),39) for i in range(2817)]
tables['ifw_alpha_table']=[q(1-math.exp(-2*math.pi*max(.1,min(20700,math.exp(-8+i/128)))/44100),30) for i in range(2561)]
knots=[(5.7,850.4219584482449),(7.7+5*(2*(48-64)/127),1443.3044461941413),
       (7.7+5*(2*(60-64)/127),2646.581370739413),(7.7,3210.0425529737995),
       (7.7+5*(2*(72-64)/127),4677.170704061711),(9.7,10254.617860351776)]
def f3(cv):
    i=1
    while i<len(knots)-1 and cv>knots[i][0]:i+=1
    x0,y0=knots[i-1];x1,y1=knots[i]
    ga=math.tan(math.pi*y0/48000);gb=math.tan(math.pi*y1/48000)
    g=ga*math.exp(math.log(gb/ga)*(cv-x0)/(x1-x0))
    hz=min(44100*.49,(48000/math.pi)*math.atan(g))
    g=math.tan(math.pi*hz/44100)
    return (g-1)/(g+1)
tables['ifw_f3_table']=[q(f3(-10+i/128),30) for i in range(3841)]
for sr,name in [(44100,'ifw_ap_table'),(22050,'ifw_ap_half_table')]:
    tables[name]=[]
    for i in range(1380):
        g=math.tan(math.pi*min(sr*.45,max(10,i*16))/sr)
        tables[name].append(q((g-1)/(g+1),30))
def shelf(gain,high):
    A=10**(gain/40);w=2*math.pi*(6000 if high else 350)/44100;c=math.cos(w)
    u=2*math.sqrt(A)*math.sin(w)/math.sqrt(2)
    if high:
        b=[A*(A+1+(A-1)*c+u),-2*A*(A-1+(A+1)*c),A*(A+1+(A-1)*c-u)]
        a=[A+1-(A-1)*c+u,2*(A-1-(A+1)*c),A+1-(A-1)*c-u]
    else:
        b=[A*(A+1-(A-1)*c+u),2*A*(A-1-(A+1)*c),A*(A+1-(A-1)*c-u)]
        a=[A+1+(A-1)*c+u,-2*(A-1+(A+1)*c),A+1+(A-1)*c-u]
    return [q(x/a[0],28) for x in b+a[1:]]
for high,name in [(False,'ifw_eq_low_table'),(True,'ifw_eq_high_table')]:
    tables[name]=sum([shelf(-12+i/10,high) for i in range(241)],[])
data='/* Generated by tools/generate_fixed_tables.py. */\n'
for name,values in tables.items():
    typ='uint64_t' if name=='ifw_glide_recip' else 'uint32_t' if name in ['ifw_semitone_fraction','ifw_octave_fraction','ifw_note_base'] else 'int32_t'
    data+=f'static const {typ} {name}[] = {{\n'
    data+=',\n'.join('    '+', '.join(str(x)+('ULL' if typ=='uint64_t' else 'u' if typ=='uint32_t' else '') for x in values[i:i+8]) for i in range(0,len(values),8))+'\n};\n'
(F/'math_tables.h').write_text(data)
# Target-only IDs avoid bringing the desktop double-based parameter typedef into firmware.
spec=json.loads((R/'docs/parameters.json').read_text())
ids='/* Generated parameter IDs, common with desktop reference. */\n#ifndef IFW_FIXED_PARAM_IDS_H\n#define IFW_FIXED_PARAM_IDS_H\nenum {\n'
ids+=''.join(f'    P_{r["name"]} = {r["id"]},\n' for r in spec)
ids+=f'    IFW_PARAM_COUNT = {len(spec)}\n}};\n'
ids+='#define IFW_OSC_STRIDE 12\n#define IFW_FILTER_STRIDE 6\n#define IFW_EG_STRIDE 5\n#define IFW_LFO_STRIDE 6\n#define IFW_MOD_STRIDE 4\n#endif\n'
(F/'param_ids.h').write_text(ids)
print('generated fixed math tables:',sum(len(v)*(8 if k=='ifw_glide_recip' else 4) for k,v in tables.items()),'bytes')
