#!/usr/bin/env python3
"""Generate typed panel controls; every patch word is reachable from the panel."""
import json,re
from pathlib import Path
from fixed_patch import SPEC,FX_KEYS,source,destination,text_value,q16
R=Path(__file__).resolve().parents[1]
choices=[]
def option(items):
    id=len(choices)+1;choices.append(items);return id
boolean=option([('OFF',0),('ON',1)])
wave=option([(x,i) for i,x in enumerate(['SIN','TRI','SAW','SQU','Ext In'])])
filtertype=option([(x,i) for i,x in enumerate(['LPF24','LPF12','HPF12','BPF12'])])
route=option([('PARALLEL 2',0),('SERIAL',1),('PARALLEL 1',2)])
br=option([('BREATH',0)]+[(f'BR x EG{i}',i) for i in range(1,5)])
glide=option([('TIME',0),('RATE',1)])
beats=option([(x,text_value('Lfo1Beat',x)) for x in ['1/1','1/2','1/4','1/8','1/16','1/32','3/16','3/8']])
src=['None','BREATH','BREATH (+-)','VELOCITY','VELOCITY (+-)','NOTE','NOTE (+-)','PITCH BEND','PITCH BEND (+-)','VIBRATO','GLIDE','GATE']
src += [f'EG {i}{b}' for i in range(1,5) for b in ['', ' (+-)']]+[f'LFO {i}{b}' for i in range(1,3) for b in ['', ' (+-)']]
src += [f'OSC {i} {w}{b}' for i in range(1,5) for w in ['SAW','TRI','PWM'] for b in ['', ' (+-)']]+['OSC 4 NOISE','OSC 4 NOISE (+-)']
sources=option([(x.replace(' (+-)',' +/-'),source(x)) for x in src])
destinations=option([('NONE',-1)]+[(x['label'].upper(),destination(x['label'])) for x in json.loads((R/'docs/modulation-destinations.json').read_text()) if destination(x['label'])>=0])
rows=[]
for p in SPEC:
    key=p['name'];enum=0;bounds=p['bounds'] or ([0,1000] if p['kind']=='number' else [0,1]);step=.1
    if p['kind']=='text':
        enum=sources if key.endswith(('Source1','Source2')) else destinations if key.endswith('Destination') else br if key.endswith('BreathSubMod') else wave if 'Waveform' in key else filtertype if key.endswith('Type') else route if key=='FilterConnection' else glide if key=='GlideMode' else beats if key.endswith('Beat') else boolean
        bounds=[0,len(choices[enum-1])-1];step=1
    else:
        bounds=[q16(x) for x in bounds];step=q16(1 if key.endswith(('Semi','Stage')) or key=='Transpose' else .1)
    label=re.sub(r'([a-z0-9])([A-Z])',r'\1 \2',key).upper().replace('WAVEFORM2','WAVE').replace('WAVEFORM','WAVE').replace('BREATH SUB MOD','BR SOURCE').replace('MINIMUM','MIN').replace('SMOOTH TIME','SMOOTH').replace('DESTINATION','DEST').replace('FREQUENCY','FREQ').replace('RESONANCE','RES').replace('CONNECTION','ROUTE')
    rows.append((label,*bounds,step,enum))
for i in range(5):
    for k in FX_KEYS:
        lo,hi,step,enum=0,10*65536,6554,0
        if k=='Bypass':lo,hi,step,enum=0,1,1,boolean
        if k in ['Lowpass','Highpass'] and i:lo,hi,step=10*65536,20000*65536,100*65536
        if k=='Time':lo,hi,step=66,65536,655
        if k in ['Speed','Rate']:lo,hi,step=655,10*65536,6554
        rows.append((f'{["PHASER","CHORUS","DELAY 1","DELAY 2","REVERB"][i]} {k.upper()}',lo,hi,step,enum))
rows += [('TUNING HZ',300*65536,500*65536,6554,0),('CHORUS PHASE',0,411775,6554,0),('FX BYPASS MASK',0,31,1,0)]
rows += [('WIND / CC7',0,1,1,boolean),('MIDI CHANNEL',0,16,1,0),('KEY OCTAVE',0,6,1,0),('SAVE SLOT',0,2,1,0)]
rows += [('RENDER MAX US',0,10000,1,0),('XRUN BLOCKS',0,2147483647,1,0),('SAMPLE RATE',44100,44100,1,0),('BUILD X1000',300,300,1,0)]
out='/* Generated by tools/generate_panel.py */\n'
out+='typedef struct {const char *label;int32_t value;} IFWOption;\n'
for i,items in enumerate(choices,1):out+=f'static const IFWOption choices_{i}[]={{'+','.join('{'+json.dumps(label)+','+str(v)+'}' for label,v in items)+'};\n'
out+='static const IFWOption *const options[]={0,'+','.join(f'choices_{i}' for i in range(1,len(choices)+1))+'};\n'
out+='static const uint16_t option_count[]={0,'+','.join(str(len(x)) for x in choices)+'};\n'
out+='typedef struct {const char *name;int32_t lo,hi,step;uint8_t choice;} IFWPanelParam;\n'
out+='static const IFWPanelParam panel_params[]={\n'+',\n'.join('{'+json.dumps(x[0])+','+','.join(str(y) for y in x[1:])+'}' for x in rows)+'\n};\n'
(R/'firmware/src/panel_params.h').write_text(out)
(R/'docs/panel-controls.json').write_text(json.dumps({'controls':[{'label':r[0],'lo':r[1],'hi':r[2],'step':r[3],'choice':r[4]} for r in rows],'choices':[[]]+[[{'label':label,'value':value} for label,value in items] for items in choices]},indent=2)+'\n')
print('generated',len(rows),'panel controls')
