#!/usr/bin/env python3
"""Exact Terminus Bold BDF pixels at 1x / 2x, in our existing 4-bit canvas format.
No font rasterizer dependency, antialiasing, fractional scaling or runtime TTF.
Font copyright Dimitar Toshkov Zhekov; SIL OFL 1.1, assets/fonts/OFL-Terminus.txt.
"""
from pathlib import Path
import argparse
R=Path(__file__).resolve().parents[1]
def cells():
    lines=(R/'assets/fonts/ter-u16b.bdf').read_text().splitlines()
    cw,ch,fx,fy=map(int,next(l for l in lines if l.startswith('FONTBOUNDINGBOX ')).split()[1:])
    assert (cw,ch)==(8,16)
    result={};code=None
    for i,l in enumerate(lines):
        if l.startswith('ENCODING '):code=int(l.split()[1])
        elif l.startswith('BBX '):bw,bh,bx,by=map(int,l.split()[1:])
        elif l=='BITMAP':
            cell=[[0]*cw for _ in range(ch)];top=ch+fy-by-bh
            for y,hexrow in enumerate(lines[i+1:i+1+bh]):
                row=int(hexrow,16)
                for x in range(bw):
                    xx,yy=bx+x,top+y
                    if 0<=xx<cw and 0<=yy<ch:cell[yy][xx]=15 if row>>(8*((bw+7)//8)-1-x)&1 else 0
            result[code]=cell
    return result

def generate():
    font=cells();out=['/* Terminus Bold by Dimitar Toshkov Zhekov, SIL OFL 1.1.',
        ' * See assets/fonts/OFL-Terminus.txt. Generated by tools/generate_ui_font.py.',
        ' * Exact 8x16 pixels / integer 2x; uppercase display like SLOOP. */']
    for name,scale in [('UI_S',1),('UI_L',2)]:
        data=[];offset=[];seen={}
        for code in range(32,127):
            source=code-32 if 97<=code<=122 else code
            if source not in seen:
                seen[source]=len(data)
                for row in font[source]:
                    expanded=[v for v in row for _ in range(scale)]
                    for _ in range(scale):data.extend((expanded[x]<<4)|expanded[x+1] for x in range(0,8*scale,2))
            offset.append(seen[source])
        for suffix,values,typ in [('DATA',data,'uint8_t'),('ADV',[8*scale]*95,'uint8_t'),('BW',[8*scale]*95,'uint8_t'),('OFF',offset,'uint16_t')]:
            out.append(f'static const {typ} {name}_{suffix}[]={{'+','.join(map(str,values))+'};')
        out.append(f'static const felucca_font_t {name}={{ {16*scale},0,32,126,{name}_ADV,{name}_BW,{name}_OFF,{name}_DATA }};')
    out.append('#define UI_M UI_S')
    return '\n'.join(out)+'\n'
if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');a=p.parse_args()
    output=generate();path=R/'firmware/src/ui/font.h'
    if a.check:assert path.read_text()==output,'UI font differs from the pinned BDF pixels'
    else:path.write_text(output)
    print('PASS exact Terminus Bold 8x16 / 16x32 font bitmaps' if a.check else 'Generated Terminus Bold UI font bitmaps')
